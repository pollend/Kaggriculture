"""Episode ring buffer that featurizes minibatches on demand.

Samples are `(episode, t, unit)` triples. The features the network sees are
rebuilt from the stored globals and job statics plus a freshly computed distance
column -- which is exactly what the agent computed live, and a test pins that
equivalence, since the whole memory saving rests on it.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from agents.dqn_job_scorer import features as F
from agents.dqn_job_scorer.market_policy import MARKET_FEATURE_DIM, assemble_market
from agents.dqn_job_scorer.rules import PRODUCTS
from agents.dqn_job_scorer.training.collect import EpisodeRecord


@dataclass
class Batch:
    """One training minibatch.

    `next_features` / `next_mask` are padded to the widest candidate set in the
    batch; masked slots must be excluded from the max, not merely zeroed, or a
    padded row would win whenever every real Q is negative.
    """

    features: np.ndarray        # float32 [B, FEATURE_DIM]        chosen action
    next_features: np.ndarray   # float32 [B, J, FEATURE_DIM]     candidates at t+n
    next_mask: np.ndarray       # bool    [B, J]
    reward: np.ndarray          # float32 [B]                     n-step discounted
    discount: np.ndarray        # float32 [B]                     gamma**n, 0 if terminal


@dataclass
class MarketBatch:
    features: np.ndarray
    next_features: np.ndarray
    next_mask: np.ndarray
    reward: np.ndarray
    discount: np.ndarray


class ReplayBuffer:
    """Recent episodes plus a uniform sample of everything older.

    A plain FIFO ring turns over in `capacity / episodes_per_round` rounds -- 12.5
    at the settings that produced run dqn03 -- so the network only ever trains on
    data generated by roughly its current policy. With a replay ratio near 8 that
    is a standard recipe for catastrophic forgetting, and it matched what dqn03
    did: flat loss throughout while greedy evaluation swung between +2,402 and
    -21,344 from one checkpoint to the next.

    So the buffer is split. A FIFO segment keeps recent, on-policy data; a
    reservoir segment holds a uniform sample of every episode ever evicted
    (Vitter's Algorithm R), at fixed memory cost. The network keeps seeing states
    its earlier selves visited, which is exactly what pure recency throws away.
    """

    def __init__(
        self,
        capacity: int = 800,
        gamma: float = 0.997,
        n_step: int = 3,
        seed: int = 0,
        reservoir_fraction: float = 0.35,
    ):
        if not 0.0 <= reservoir_fraction < 1.0:
            raise ValueError("reservoir_fraction must be in [0, 1)")
        self.capacity = capacity
        self.gamma = gamma
        self.n_step = n_step
        self.reservoir_capacity = int(capacity * reservoir_fraction)
        self.recent_capacity = capacity - self.reservoir_capacity
        self.recent: list[EpisodeRecord] = []
        self.reservoir: list[EpisodeRecord] = []
        self.evicted_seen = 0
        self.rng = np.random.default_rng(seed)

    def add(self, records: list[EpisodeRecord]) -> None:
        for record in records:
            self.recent.append(record)
            if len(self.recent) > self.recent_capacity:
                self._offer_to_reservoir(self.recent.pop(0))

    def _offer_to_reservoir(self, record: EpisodeRecord) -> None:
        """Algorithm R over the eviction stream: a uniform sample of all history."""
        if self.reservoir_capacity == 0:
            return
        self.evicted_seen += 1
        if len(self.reservoir) < self.reservoir_capacity:
            self.reservoir.append(record)
            return
        index = int(self.rng.integers(0, self.evicted_seen))
        if index < self.reservoir_capacity:
            self.reservoir[index] = record

    @property
    def episodes(self) -> list[EpisodeRecord]:
        return self.recent + self.reservoir

    @property
    def transitions(self) -> int:
        return sum(int(record.unit_mask.sum()) for record in self.episodes)

    @property
    def market_transitions(self) -> int:
        return sum(0 if record.market_step is None else len(record.market_step) for record in self.episodes)

    def nbytes(self) -> int:
        return sum(record.nbytes() for record in self.episodes)

    def _features_at(self, record: EpisodeRecord, t: int, unit: int) -> tuple[np.ndarray, np.ndarray]:
        """Rebuild the candidate feature matrix this unit faced at step t."""
        mask = record.job_mask[t]
        count = int(mask.sum())
        static = record.job_static[t, :count].astype(np.float32)
        targets = record.job_targets[t, :count]
        position = (int(record.unit_pos[t, unit, 0]), int(record.unit_pos[t, unit, 1]))
        distance = F.distance_features(targets, position, int(record.committed[t, unit]))
        return (
            F.assemble(record.global_feats[t], static, distance),
            record.available[t, unit, :count],
        )

    def sample(self, batch_size: int) -> Batch:
        # Snapshot once: `episodes` concatenates two lists, and this is the hot loop.
        episodes = self.episodes
        episode_indices = self.rng.integers(0, len(episodes), size=batch_size)

        chosen_features = np.empty((batch_size, F.FEATURE_DIM), dtype=np.float32)
        rewards = np.zeros(batch_size, dtype=np.float32)
        discounts = np.zeros(batch_size, dtype=np.float32)
        next_sets: list[np.ndarray] = []
        next_masks: list[np.ndarray] = []

        for row, episode_index in enumerate(episode_indices):
            record = episodes[int(episode_index)]
            steps = record.steps
            t = int(self.rng.integers(0, steps))
            units = np.flatnonzero(record.unit_mask[t])
            unit = int(self.rng.choice(units))

            features, _ = self._features_at(record, t, unit)
            chosen_features[row] = features[int(record.chosen[t, unit])]

            # n-step return, truncated at the episode end.
            horizon = min(self.n_step, steps - t)
            discount = 1.0
            total = 0.0
            for offset in range(horizon):
                total += discount * float(record.reward[t + offset])
                discount *= self.gamma
            rewards[row] = total

            bootstrap = t + horizon
            if bootstrap >= steps:
                discounts[row] = 0.0  # terminal: nothing left to bootstrap from
                next_sets.append(np.zeros((1, F.FEATURE_DIM), dtype=np.float32))
                next_masks.append(np.zeros(1, dtype=bool))
                continue

            discounts[row] = discount
            # The acting unit may not exist at t+n (hands are re-hired daily), so
            # fall back to the main farmer, which always exists.
            next_units = np.flatnonzero(record.unit_mask[bootstrap])
            next_unit = unit if unit in next_units else int(next_units[0])
            next_features, candidate_mask = self._features_at(record, bootstrap, next_unit)
            next_sets.append(next_features)
            next_masks.append(candidate_mask)

        width = max(candidates.shape[0] for candidates in next_sets)
        next_features = np.zeros((batch_size, width, F.FEATURE_DIM), dtype=np.float32)
        next_mask = np.zeros((batch_size, width), dtype=bool)
        for row, (candidates, candidate_mask) in enumerate(zip(next_sets, next_masks)):
            count = candidates.shape[0]
            next_features[row, :count] = candidates
            next_mask[row, :count] = candidate_mask

        return Batch(chosen_features, next_features, next_mask, rewards, discounts)

    def _market_candidates_at(self, record: EpisodeRecord, decision: int) -> tuple[list[np.ndarray], list[np.ndarray]]:
        assert record.market_state is not None
        assert record.market_purchase_static is not None
        assert record.market_purchase_mask is not None
        assert record.market_reserve_static is not None
        assert record.market_reserve_mask is not None
        state = record.market_state[decision]
        candidates = [assemble_market(state, record.market_purchase_static[decision])]
        masks = [record.market_purchase_mask[decision]]
        for product_index in range(len(PRODUCTS)):
            candidates.append(assemble_market(state, record.market_reserve_static[decision, product_index]))
            masks.append(record.market_reserve_mask[decision, product_index])
        return candidates, masks

    def sample_market(self, batch_size: int) -> MarketBatch:
        eligible = [record for record in self.episodes if record.market_step is not None and len(record.market_step)]
        if not eligible:
            raise ValueError("market replay has no schema-v4 daily decisions")
        factor_count = 1 + len(PRODUCTS)
        selected = np.zeros((batch_size, factor_count, MARKET_FEATURE_DIM), dtype=np.float32)
        rewards = np.zeros(batch_size, dtype=np.float32)
        discounts = np.zeros(batch_size, dtype=np.float32)
        future: list[list[np.ndarray] | None] = []
        future_masks: list[list[np.ndarray] | None] = []
        for row in range(batch_size):
            record = eligible[int(self.rng.integers(0, len(eligible)))]
            assert record.market_step is not None and record.market_chosen is not None
            decision = int(self.rng.integers(0, len(record.market_step)))
            candidates, _ = self._market_candidates_at(record, decision)
            for factor in range(factor_count):
                selected[row, factor] = candidates[factor][int(record.market_chosen[decision, factor])]

            horizon = min(self.n_step, len(record.market_step) - decision)
            bootstrap = decision + horizon
            start_step = int(record.market_step[decision])
            end_step = int(record.market_step[bootstrap]) if bootstrap < len(record.market_step) else record.steps
            turn_discount = 1.0
            for step in range(start_step, end_step):
                rewards[row] += turn_discount * float(record.reward[step])
                turn_discount *= self.gamma
            if bootstrap >= len(record.market_step):
                future.append(None)
                future_masks.append(None)
            else:
                discounts[row] = turn_discount
                candidates, masks = self._market_candidates_at(record, bootstrap)
                future.append(candidates)
                future_masks.append(masks)

        width = max(
            (candidate.shape[0] for rows in future if rows is not None for candidate in rows),
            default=1,
        )
        next_features = np.zeros((batch_size, factor_count, width, MARKET_FEATURE_DIM), dtype=np.float32)
        next_mask = np.zeros((batch_size, factor_count, width), dtype=bool)
        for row, (rows, masks) in enumerate(zip(future, future_masks)):
            if rows is None or masks is None:
                continue
            for factor, (candidates, mask) in enumerate(zip(rows, masks)):
                count = candidates.shape[0]
                next_features[row, factor, :count] = candidates
                next_mask[row, factor, :count] = mask
        return MarketBatch(selected, next_features, next_mask, rewards, discounts)
